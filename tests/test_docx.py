"""Test suite for Microsoft Word (.docx) export generation."""

import io
from docx import Document
from document_generator.docx_generator import generate_docx


def test_generate_docx_produces_valid_bytes():
    """Verify generate_docx returns non-empty byte stream that python-docx can open."""
    sample_content = (
        "NON-DISCLOSURE AGREEMENT\n\n"
        "SECTION 1: DEFINITIONS\n"
        "Confidential material includes trade secrets.\n\n"
        "SECTION 2: OBLIGATIONS\n"
        "Receiving party must protect data."
    )

    docx_bytes = generate_docx(sample_content, title="NON-DISCLOSURE AGREEMENT")
    assert isinstance(docx_bytes, bytes)
    assert len(docx_bytes) > 0

    # Ensure python-docx can parse the generated byte buffer
    doc = Document(io.BytesIO(docx_bytes))
    paragraphs = [p.text for p in doc.paragraphs if p.text]

    assert any("NON-DISCLOSURE AGREEMENT" in p for p in paragraphs)
    assert any("SECTION 1: DEFINITIONS" in p for p in paragraphs)
    assert any("Confidential material includes trade secrets." in p for p in paragraphs)


def test_generate_docx_handles_empty_content():
    """Verify generate_docx handles empty content without crashing."""
    docx_bytes = generate_docx("", title="EMPTY AGREEMENT")
    assert isinstance(docx_bytes, bytes)
    assert len(docx_bytes) > 0
    doc = Document(io.BytesIO(docx_bytes))
    assert doc is not None


def test_generate_docx_with_terms_table():
    """Verify generate_docx creates structured tables when table markup is provided."""
    sample_content = (
        "CONSULTING AGREEMENT\n\n"
        "| Deliverable | Due Date |\n"
        "| Architecture Plan | 2026-11-01 |\n"
        "| Final Code Delivery | 2026-12-15 |\n\n"
        "SECTION 1: FEES\n"
        "Consultant shall be paid on Net 30 terms."
    )
    docx_bytes = generate_docx(sample_content, title="CONSULTING AGREEMENT")
    doc = Document(io.BytesIO(docx_bytes))
    assert len(doc.tables) >= 1
    table = doc.tables[0]
    assert len(table.rows) == 4  # Header + 3 rows
    row1_text = [c.text.strip() for c in table.rows[1].cells]
    assert "Deliverable" in row1_text[0]

